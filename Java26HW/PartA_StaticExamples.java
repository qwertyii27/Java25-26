public class PartA_StaticExamples {
  // An example of a static variable is Math.PI. An example of a static method is
  // Math.round. This small program rounds pi.
  public static void main(String[] args) {
    double roundPi = Math.round(Math.PI);
    System.out.println("Rounded pi is: " + roundPi);
  }
}
